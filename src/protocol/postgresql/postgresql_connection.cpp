void client::append_insert_returning(std::string& sql, std::string_view column) const
{
    sql += " RETURNING \"";
    for (char c : column)
    {
        if (c == '"')
            sql += "\"\"";
        else
            sql.push_back(c);
    }
    sql += '"';
}

