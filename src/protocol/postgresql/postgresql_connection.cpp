auto client::connect(connection_options options) -> task<result_set>
{
    if (operation_in_progress_.test_and_set(std::memory_order_acquire))
        co_return make_error("another PostgreSQL operation is already in progress");
    operation_guard guard{operation_in_progress_};
    disconnect();
    options_ = std::move(options);
    if (options_.maximum_message_size < 8 || options_.maximum_message_size > 1024ULL * 1024 * 1024)
        co_return make_error("maximum_message_size is outside the supported range");

    happy_eyeballs_options connect_options;
    connect_options.connect_timeout = options_.connect_timeout;
    connect_options.socket_opts.no_delay = true;
    const auto maximum_attempts = std::max<std::size_t>(
        1, options_.maximum_connect_attempts);
    std::expected<connect_result, std::error_code> connected =
        std::unexpected(std::make_error_code(std::errc::host_unreachable));
    for (std::size_t attempt = 1; attempt <= maximum_attempts; ++attempt)
    {
        connected = co_await async_connect_happy_eyeballs(
            context_, options_.host, options_.port, connect_options);
        if (connected || !retryable_connect_error(connected.error()) ||
            attempt == maximum_attempts)
            break;
        co_await async_sleep(context_, options_.connect_retry_backoff * static_cast<int>(attempt));
    }
    if (!connected)
    {
        last_error_ = connected.error();
        co_return make_error("connect: " + connected.error().message());
    }
    socket_ = std::move(connected->sock);

    if (options_.tls != tls_mode::disable)
    {
#ifdef CNETMOD_HAS_SSL
        auto request = detail::ssl_request();
        if (!co_await write_all(request))
            co_return make_error("failed to send SSLRequest");
        std::uint8_t response{};
        if (!co_await read_exact(&response, 1))
            co_return make_error("failed to read SSL negotiation response");
        if (response == 'S')
        {
            auto context = ssl_context::client();
            if (!context)
            {
                disconnect();
                co_return make_error("TLS context: " + context.error().message());
            }
            ssl_context_ = std::make_unique<ssl_context>(std::move(*context));
            const bool verify = options_.tls == tls_mode::verify_ca || options_.tls == tls_mode::verify_full;
            ssl_context_->set_verify_peer(verify);
            if (!options_.tls_ca_file.empty())
            {
                if (auto loaded = ssl_context_->load_ca_file(options_.tls_ca_file); !loaded)
                {
                    disconnect();
                    co_return make_error("failed to load PostgreSQL CA file");
                }
            }
            else if (verify)
            {
                if (auto loaded = ssl_context_->set_default_ca(); !loaded)
                {
                    disconnect();
                    co_return make_error("failed to load system CA certificates");
                }
            }
            if (!options_.tls_cert_file.empty() && !ssl_context_->load_cert_file(options_.tls_cert_file))
            {
                disconnect();
                co_return make_error("failed to load PostgreSQL client certificate");
            }
            if (!options_.tls_key_file.empty() && !ssl_context_->load_key_file(options_.tls_key_file))
            {
                disconnect();
                co_return make_error("failed to load PostgreSQL client key");
            }
            ssl_stream_ = std::make_unique<ssl_stream>(*ssl_context_, context_, socket_);
            ssl_stream_->set_connect_state();
            if (options_.tls == tls_mode::verify_full)
                ssl_stream_->set_hostname(options_.host);
            auto handshake = co_await ssl_stream_->async_handshake();
            if (!handshake)
            {
                auto message = handshake.error().message();
                disconnect(handshake.error());
                co_return make_error("TLS handshake: " + message);
            }
            secure_ = true;
        }
        else if (response != 'N')
        {
            disconnect();
            co_return make_error("invalid SSL negotiation response");
        }
        else if (options_.tls != tls_mode::prefer)
        {
            disconnect();
            co_return make_error("PostgreSQL server rejected required TLS");
        }
#else
        if (options_.tls != tls_mode::prefer)
        {
            disconnect();
            co_return make_error("TLS requested but cnetmod was built without OpenSSL");
        }
#endif
    }

    auto startup = detail::startup_message(options_);
    if (!co_await write_all(startup))
        co_return make_error("failed to send StartupMessage");
    auto authenticated = co_await authenticate();
    if (authenticated.is_err())
        disconnect();
    co_return authenticated;
}

auto client::reconnect() -> task<result_set>
{
    auto saved = options_;
    disconnect();
    co_return co_await connect(std::move(saved));
}

auto client::authenticate() -> task<result_set>
{
    detail::scram_client scram;
    bool scram_started{};
    for (;;)
    {
        auto message = co_await read_message();
        if (!message)
            co_return make_error(message.error());
        auto payload = std::span<const std::uint8_t>(message->payload);
        if (message->type == 'R')
        {
            if (payload.size() < 4)
                co_return make_error("truncated AuthenticationRequest");
            const auto method = read_u32(payload.first(4));
            if (method == 0)
                continue;
            if (method == 3)
            {
                if (!secure_)
                    co_return make_error("cleartext password authentication is refused without TLS");
                if (!co_await write_all(detail::password_message(options_.password)))
                    co_return make_error("failed to send password");
            }
            else if (method == 5)
            {
                if (payload.size() != 8)
                    co_return make_error("invalid MD5 authentication request");
                auto password = detail::md5_password(options_.username, options_.password,
                    std::span<const std::uint8_t, 4>(payload.subspan(4, 4)));
                if (!password)
                    co_return make_error(password.error());
                if (!co_await write_all(detail::password_message(*password)))
                    co_return make_error("failed to send MD5 password");
            }
            else if (method == 10)
            {
                bool supports_sha256{};
                std::size_t position = 4;
                while (position < payload.size())
                {
                    auto mechanism = read_cstring(payload, position);
                    if (!mechanism || mechanism->empty())
                        break;
                    if (*mechanism == "SCRAM-SHA-256")
                        supports_sha256 = true;
                }
                if (!supports_sha256)
                    co_return make_error("server does not offer SCRAM-SHA-256");
                std::string first;
                try
                {
                    first = scram.begin(options_.username);
                }
                catch (const std::exception& error)
                {
                    co_return make_error(error.what());
                }
                scram_started = true;
                if (!co_await write_all(detail::scram_initial_response("SCRAM-SHA-256", first)))
                    co_return make_error("failed to send SCRAM initial response");
            }
            else if (method == 11 && scram_started)
            {
                std::string challenge(reinterpret_cast<const char*>(payload.data() + 4), payload.size() - 4);
                auto response = scram.respond(options_.password, challenge);
                if (!response)
                    co_return make_error(response.error());
                if (!co_await write_all(detail::scram_response(*response)))
                    co_return make_error("failed to send SCRAM proof");
            }
            else if (method == 12 && scram_started)
            {
                std::string final_message(reinterpret_cast<const char*>(payload.data() + 4), payload.size() - 4);
                if (auto verified = scram.verify(final_message); !verified)
                    co_return make_error(verified.error());
            }
            else
                co_return make_error(std::format("unsupported PostgreSQL authentication method {}", method));
        }
        else if (message->type == 'E')
        {
            auto error = detail::parse_error(payload);
            co_return make_error(error.message.empty() ? "PostgreSQL authentication failed" : error.message, error.sql_state);
        }
        else if (message->type == 'S')
        {
            std::size_t position{};
            auto key = read_cstring(payload, position);
            auto value = read_cstring(payload, position);
            if (key && value)
                parameters_.insert_or_assign(std::move(*key), std::move(*value));
        }
        else if (message->type == 'K' && payload.size() == 8)
        {
            process_id_ = read_u32(payload.first(4));
            secret_key_ = read_u32(payload.subspan(4));
        }
        else if (message->type == 'Z')
        {
            connected_ = true;
            transaction_failed_ = !payload.empty() && payload[0] == 'E';
            co_return result_set{};
        }
    }
}

auto client::query(std::string_view sql) -> task<result_set>
{
    if (!connected_)
        co_return make_error("not connected");
    if (operation_in_progress_.test_and_set(std::memory_order_acquire))
        co_return make_error("another PostgreSQL operation is already in progress");
    operation_guard guard{operation_in_progress_};
    auto command = detail::simple_query_message(normalized_sql(sql));
    if (!co_await write_all(command))
        co_return make_error("failed to send query");
    co_return co_await collect_results();
}

auto client::execute(std::string_view sql) -> task<result_set>
{
    return query(sql);
}

auto client::execute(parameterized_query parameters) -> task<result_set>
{
    if (!connected_)
        co_return make_error("not connected");
    if (operation_in_progress_.test_and_set(std::memory_order_acquire))
        co_return make_error("another PostgreSQL operation is already in progress");
    operation_guard guard{operation_in_progress_};
    const auto sql = normalized_sql(parameters.query);
    if (detail::count_postgresql_parameters(sql) != parameters.args.size())
        co_return make_error("PostgreSQL parameter count mismatch");
    auto messages = detail::extended_query_messages({}, sql, parameters.args, true);
    if (messages.size() > options_.maximum_message_size)
        co_return make_error("parameterized query exceeds maximum_message_size");
    if (!co_await write_all(messages))
        co_return make_error("failed to send parameterized query");
    co_return co_await collect_results();
}

auto client::prepare(std::string_view sql, std::string name)
    -> task<std::expected<prepared_statement, std::string>>
{
    if (!connected_)
        co_return std::unexpected("not connected");
    if (operation_in_progress_.test_and_set(std::memory_order_acquire))
        co_return std::unexpected("another PostgreSQL operation is already in progress");
    operation_guard guard{operation_in_progress_};
    if (name.empty())
        name = std::format("cnetmod_{}", ++statement_counter_);
    if (name.find('\0') != std::string::npos)
        co_return std::unexpected("statement name contains NUL");
    const auto normalized = normalized_sql(sql);
    const auto parameter_count = detail::count_postgresql_parameters(normalized);
    if (parameter_count > 65535)
        co_return std::unexpected("PostgreSQL supports at most 65535 statement parameters");
    auto messages = detail::prepare_statement_messages(name, normalized);
    if (messages.size() > options_.maximum_message_size)
        co_return std::unexpected("prepared statement exceeds maximum_message_size");
    if (!co_await write_all(messages))
        co_return std::unexpected("failed to send Parse message");
    auto result = co_await collect_results();
    if (result.is_err())
        co_return std::unexpected(result.error_msg);
    co_return prepared_statement{std::move(name), normalized, parameter_count};
}

auto client::execute(const prepared_statement& statement,
    std::span<const param_value> parameters) -> task<result_set>
{
    if (!connected_)
        co_return make_error("not connected");
    if (!statement.valid())
        co_return make_error("invalid prepared statement");
    if (parameters.size() != statement.parameter_count)
        co_return make_error("prepared statement parameter count mismatch");
    if (operation_in_progress_.test_and_set(std::memory_order_acquire))
        co_return make_error("another PostgreSQL operation is already in progress");
    operation_guard guard{operation_in_progress_};
    auto messages = detail::extended_query_messages(statement.name, {}, parameters, false);
    if (!co_await write_all(messages))
        co_return make_error("failed to bind prepared statement");
    co_return co_await collect_results();
}

auto client::close_statement(const prepared_statement& statement) -> task<result_set>
{
    if (!connected_)
        co_return make_error("not connected");
    if (operation_in_progress_.test_and_set(std::memory_order_acquire))
        co_return make_error("another PostgreSQL operation is already in progress");
    operation_guard guard{operation_in_progress_};
    std::vector<std::uint8_t> message{'C', 0, 0, 0, 0, 'S'};
    message.insert(message.end(), statement.name.begin(), statement.name.end());
    message.push_back(0);
    const auto length = static_cast<std::uint32_t>(message.size() - 1);
    message[1] = static_cast<std::uint8_t>(length >> 24);
    message[2] = static_cast<std::uint8_t>(length >> 16);
    message[3] = static_cast<std::uint8_t>(length >> 8);
    message[4] = static_cast<std::uint8_t>(length);
    message.insert(message.end(), {'S', 0, 0, 0, 4});
    if (!co_await write_all(message))
        co_return make_error("failed to close prepared statement");
    co_return co_await collect_results();
}

auto client::copy_from(std::string_view copy_sql, copy_data_source source)
    -> task<result_set>
{
    if (!connected_)
        co_return make_error("not connected");
    if (!source)
        co_return make_error("COPY source callback is empty");
    if (operation_in_progress_.test_and_set(std::memory_order_acquire))
        co_return make_error("another PostgreSQL operation is already in progress");
    operation_guard guard{operation_in_progress_};
    if (!co_await write_all(detail::simple_query_message(normalized_sql(copy_sql))))
        co_return make_error("failed to start COPY FROM STDIN");
    auto response = co_await read_message();
    if (!response)
        co_return make_error(response.error());
    if (response->type == 'E')
    {
        auto error = detail::parse_error(response->payload);
        co_return make_error(error.message, error.sql_state);
    }
    if (response->type != 'G')
        co_return make_error("server did not enter COPY FROM STDIN mode");
    std::string copy_failure;
    for (;;)
    {
        std::optional<std::vector<std::uint8_t>> chunk;
        try
        {
            chunk = co_await source();
        }
        catch (const std::exception& error)
        {
            copy_failure = error.what();
            break;
        }
        catch (...)
        {
            copy_failure = "COPY source callback failed";
            break;
        }
        if (!chunk)
            break;
        if (chunk->size() + 4 > options_.maximum_message_size)
        {
            copy_failure = "COPY data chunk exceeds maximum_message_size";
            break;
        }
        std::vector<std::uint8_t> message{'d', 0, 0, 0, 0};
        const auto length = static_cast<std::uint32_t>(chunk->size() + 4);
        message[1] = static_cast<std::uint8_t>(length >> 24);
        message[2] = static_cast<std::uint8_t>(length >> 16);
        message[3] = static_cast<std::uint8_t>(length >> 8);
        message[4] = static_cast<std::uint8_t>(length);
        message.insert(message.end(), chunk->begin(), chunk->end());
        if (!co_await write_all(message))
            co_return make_error("failed to stream COPY data");
    }
    if (!copy_failure.empty())
    {
        std::vector<std::uint8_t> fail{'f', 0, 0, 0, 0};
        fail.insert(fail.end(), copy_failure.begin(), copy_failure.end());
        fail.push_back(0);
        const auto length = static_cast<std::uint32_t>(fail.size() - 1);
        fail[1] = static_cast<std::uint8_t>(length >> 24);
        fail[2] = static_cast<std::uint8_t>(length >> 16);
        fail[3] = static_cast<std::uint8_t>(length >> 8);
        fail[4] = static_cast<std::uint8_t>(length);
        if (!co_await write_all(fail))
            co_return make_error("failed to abort COPY FROM STDIN");
        auto aborted = co_await collect_results();
        if (aborted.error_msg.empty())
            aborted.error_msg = std::move(copy_failure);
        co_return aborted;
    }
    const std::array<std::uint8_t, 5> done{'c', 0, 0, 0, 4};
    if (!co_await write_all(done))
        co_return make_error("failed to finish COPY FROM STDIN");
    co_return co_await collect_results();
}

auto client::copy_to(std::string_view copy_sql, copy_data_sink sink)
    -> task<result_set>
{
    if (!connected_)
        co_return make_error("not connected");
    if (!sink)
        co_return make_error("COPY sink callback is empty");
    if (operation_in_progress_.test_and_set(std::memory_order_acquire))
        co_return make_error("another PostgreSQL operation is already in progress");
    operation_guard guard{operation_in_progress_};
    if (!co_await write_all(detail::simple_query_message(normalized_sql(copy_sql))))
        co_return make_error("failed to start COPY TO STDOUT");
    result_set result;
    bool copy_started{};
    std::exception_ptr sink_failure;
    for (;;)
    {
        auto message = co_await read_message();
        if (!message)
            co_return make_error(message.error());
        if (message->type == 'H')
            copy_started = true;
        else if (message->type == 'd')
        {
            if (!copy_started)
                co_return make_error("COPY data received before CopyOutResponse");
            if (!sink_failure)
            {
                try
                {
                    co_await sink(message->payload);
                }
                catch (...)
                {
                    sink_failure = std::current_exception();
                }
            }
        }
        else if (message->type == 'C')
        {
            std::size_t position{};
            auto tag = read_cstring(std::span<const std::uint8_t>(message->payload), position);
            if (tag)
                result.info = *tag;
        }
        else if (message->type == 'E')
        {
            auto error = detail::parse_error(message->payload);
            result.error_msg = error.message;
            result.sql_state = error.sql_state;
        }
        else if (message->type == 'Z')
        {
            if (sink_failure)
                std::rethrow_exception(sink_failure);
            co_return result;
        }
    }
}

auto client::drain_until_ready() -> task<bool>
{
    for (;;)
    {
        auto message = co_await read_message();
        if (!message)
            co_return false;
        if (message->type == 'Z')
            co_return true;
    }
}

auto client::abort_streaming_portal(std::string_view portal) -> task<void>
{
    if (!co_await write_all(detail::streaming_portal_close_messages(portal)))
    {
        disconnect();
        co_return;
    }
    if (!co_await drain_until_ready())
        disconnect();
}

auto client::deliver_batch(std::vector<row>& batch,
    const std::function<task<void>(std::span<const row>)>& consume)
    -> task<std::exception_ptr>
{
    if (batch.empty())
        co_return nullptr;
    try
    {
        co_await consume(std::span<const row>(batch));
    }
    catch (...)
    {
        batch.clear();
        co_return std::current_exception();
    }
    batch.clear();
    co_return nullptr;
}

