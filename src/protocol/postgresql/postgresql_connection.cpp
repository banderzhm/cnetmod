auto client::cancel_current_operation() -> task<result_set>
{
    if (!connected_ || process_id_ == 0 || secret_key_ == 0)
        co_return make_error("no active PostgreSQL backend key is available");
    happy_eyeballs_options connect_options;
    connect_options.connect_timeout = options_.connect_timeout;
    connect_options.socket_opts.no_delay = true;
    auto connection = co_await async_connect_happy_eyeballs(
        context_, options_.host, options_.port, connect_options);
    if (!connection)
        co_return make_error("cancel connect: " + connection.error().message());
    std::array<std::uint8_t, 16> request{};
    auto write_u32 = [&request](std::size_t offset, std::uint32_t value)
    {
        request[offset] = static_cast<std::uint8_t>(value >> 24);
        request[offset + 1] = static_cast<std::uint8_t>(value >> 16);
        request[offset + 2] = static_cast<std::uint8_t>(value >> 8);
        request[offset + 3] = static_cast<std::uint8_t>(value);
    };
    write_u32(0, 16);
    write_u32(4, 80877102);
    write_u32(8, process_id_);
    write_u32(12, secret_key_);
    auto sent = co_await async_write_all(context_, connection->sock,
        const_buffer{request.data(), request.size()});
    connection->sock.close();
    if (!sent)
        co_return make_error("failed to send PostgreSQL CancelRequest: " + sent.error().message());
    co_return result_set{};
}

auto client::collect_results() -> task<result_set>
{
    result_set result;
    std::vector<std::uint32_t> oids;
    for (;;)
    {
        auto message = co_await read_message();
        if (!message)
            co_return make_error(message.error());
        auto payload = std::span<const std::uint8_t>(message->payload);
        if (message->type == 'T')
        {
            if (payload.size() < 2)
                co_return make_error("truncated RowDescription");
            const auto count = read_u16(payload.first(2));
            if (count > options_.maximum_column_count)
                co_return make_error("PostgreSQL column limit exceeded");
            result.columns.clear();
            oids.clear();
            result.columns.reserve(count);
            oids.reserve(count);
            std::size_t position = 2;
            for (std::uint16_t i = 0; i < count; ++i)
            {
                auto name = read_cstring(payload, position);
                if (!name || position + 18 > payload.size())
                    co_return make_error("invalid RowDescription");
                column_meta column;
                column.name = *name;
                column.original_name = *name;
                const auto table_oid = read_u32(payload.subspan(position, 4));
                position += 4;
                const auto attribute = read_u16(payload.subspan(position, 2));
                position += 2;
                (void)table_oid;
                (void)attribute;
                const auto oid = read_u32(payload.subspan(position, 4));
                position += 4;
                column.native_type = oid;
                oids.push_back(oid);
                const auto width = read_u16(payload.subspan(position, 2));
                position += 2;
                column.type_size = width == 0xffff ? -1 : static_cast<std::int16_t>(width);
                column.type_modifier = static_cast<std::int32_t>(read_u32(payload.subspan(position, 4)));
                position += 4;
                column.format_code = static_cast<std::int16_t>(read_u16(payload.subspan(position, 2)));
                position += 2;
                result.columns.push_back(std::move(column));
            }
        }
        else if (message->type == 'D')
        {
            if (result.rows.size() >= options_.maximum_row_count)
                co_return make_error("PostgreSQL row limit exceeded");
            if (payload.size() < 2)
                co_return make_error("truncated DataRow");
            const auto count = read_u16(payload.first(2));
            if (count != oids.size())
                co_return make_error("DataRow column count mismatch");
            std::size_t position = 2;
            row values;
            values.reserve(count);
            for (std::size_t i = 0; i < count; ++i)
            {
                if (position + 4 > payload.size())
                    co_return make_error("truncated DataRow field length");
                const auto length = read_u32(payload.subspan(position, 4));
                position += 4;
                if (length == 0xffffffffU)
                {
                    values.push_back(field_value::null());
                    continue;
                }
                if (length > payload.size() - position)
                    co_return make_error("invalid DataRow field length");
                std::string_view value(reinterpret_cast<const char*>(payload.data() + position), length);
                values.push_back(detail::decode_text_field(oids[i], value));
                position += length;
            }
            result.rows.push_back(std::move(values));
        }
        else if (message->type == 'C')
        {
            std::size_t position{};
            auto tag = read_cstring(payload, position);
            if (tag)
            {
                result.info = *tag;
                auto split = tag->find_last_of(' ');
                if (split != std::string::npos)
                {
                    std::uint64_t count{};
                    auto parsed = std::from_chars(tag->data() + split + 1, tag->data() + tag->size(), count);
                    if (parsed.ec == std::errc{})
                        result.affected_rows = count;
                }
            }
        }
        else if (message->type == 'E')
        {
            auto error = detail::parse_error(payload);
            result.error_msg = error.message.empty() ? "PostgreSQL query failed" : error.message;
            if (!error.detail.empty())
                result.error_msg += ": " + error.detail;
            result.sql_state = error.sql_state;
        }
        else if (message->type == 'S')
        {
            std::size_t position{};
            auto key = read_cstring(payload, position);
            auto value = read_cstring(payload, position);
            if (key && value)
                parameters_.insert_or_assign(std::move(*key), std::move(*value));
        }
        else if (message->type == 'K' && payload.size() == 8)
        {
            process_id_ = read_u32(payload.first(4));
            secret_key_ = read_u32(payload.subspan(4));
        }
        else if (message->type == 'Z')
        {
            transaction_failed_ = !payload.empty() && payload[0] == 'E';
            if (!result.rows.empty() && !result.rows.front().empty())
            {
                const auto& value = result.rows.front().front();
                if (value.is_int64() && value.get_int64() >= 0)
                    result.last_insert_id = static_cast<std::uint64_t>(value.get_int64());
                else if (value.is_uint64())
                    result.last_insert_id = value.get_uint64();
            }
            co_return result;
        }
    }
}

auto client::terminate() -> task<void>
{
    if (connected_)
    {
        auto message = detail::terminate_message();
        (void)co_await write_all(message);
#ifdef CNETMOD_HAS_SSL
        if (ssl_stream_)
            (void)co_await ssl_stream_->async_shutdown();
#endif
    }
    disconnect();
    co_return;
}

auto client::write_all(std::span<const std::uint8_t> bytes) -> task<bool>
{
    if (bytes.empty() || bytes.size() > options_.maximum_message_size)
    {
        disconnect(std::make_error_code(std::errc::message_size));
        co_return false;
    }
    const_buffer buffer{bytes.data(), bytes.size()};
#ifdef CNETMOD_HAS_SSL
    if (ssl_stream_)
    {
        auto written = co_await ssl_stream_->async_write_all(buffer);
        if (!written)
        {
            disconnect(written.error());
            co_return false;
        }
        co_return true;
    }
#endif
    auto written = co_await async_write_all(context_, socket_, buffer);
    if (!written)
    {
        disconnect(written.error());
        co_return false;
    }
    co_return true;
}

auto client::read_exact(std::uint8_t* destination, std::size_t length) -> task<bool>
{
    std::size_t received{};
    while (received < length)
    {
        mutable_buffer buffer{destination + received, length - received};
#ifdef CNETMOD_HAS_SSL
        std::expected<std::size_t, std::error_code> part;
        if (ssl_stream_)
            part = co_await ssl_stream_->async_read(buffer);
        else
            part = co_await async_read(context_, socket_, buffer);
#else
        auto part = co_await async_read(context_, socket_, buffer);
#endif
        if (!part || *part == 0)
        {
            disconnect(part ? std::make_error_code(std::errc::connection_reset) : part.error());
            co_return false;
        }
        received += *part;
    }
    co_return true;
}

auto client::read_message() -> task<std::expected<detail::backend_message, std::string>>
{
    std::array<std::uint8_t, 5> header{};
    if (!co_await read_exact(header.data(), header.size()))
        co_return std::unexpected("connection lost while reading PostgreSQL message");
    const auto length = read_u32(std::span<const std::uint8_t>(header).subspan(1));
    if (length < 4 || length > options_.maximum_message_size)
    {
        disconnect();
        co_return std::unexpected("invalid PostgreSQL message length");
    }
    std::vector<std::uint8_t> wire(length + 1);
    std::copy(header.begin(), header.end(), wire.begin());
    if (length > 4 && !co_await read_exact(wire.data() + 5, length - 4))
        co_return std::unexpected("connection lost while reading PostgreSQL payload");
    co_return detail::parse_message(wire);
}

void client::disconnect(std::error_code error) noexcept
{
    connected_ = false;
    secure_ = false;
    transaction_failed_ = false;
    last_error_ = error;
    parameters_.clear();
    process_id_ = 0;
    secret_key_ = 0;
#ifdef CNETMOD_HAS_SSL
    ssl_stream_.reset();
    ssl_context_.reset();
#endif
    socket_.close();
}

